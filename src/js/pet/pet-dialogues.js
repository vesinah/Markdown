// สุ่มบทสนทนาที่เหมาะสมตามบริบท วันเวลาจริงจาก PC ความทรงจำ อารมณ์ความรู้สึก และเพศ
export function getRandomDialogue(category, meta = {}) {
  const gender = meta.gender || meta.pet?.gender || 'male';

  // ตรวจสอบว่ามีหมวดหมู่คำพูดเฉพาะเพศหรือไม่
  if (PET_DIALOGUES.gendered && PET_DIALOGUES.gendered[gender] && PET_DIALOGUES.gendered[gender][category]) {
    const gList = PET_DIALOGUES.gendered[gender][category];
    if (Math.random() < 0.7) {
      const raw = gList[Math.floor(Math.random() * gList.length)];
      return formatDialogue(raw, meta);
    }
  }

  let list = PET_DIALOGUES[category] || PET_DIALOGUES.docContext;

  // 1. ตรวจจับวันเวลาจริงจาก PC
  if (category.startsWith('time') || category === 'realTime') {
    const timeCtx = (typeof PetMemory !== 'undefined' && PetMemory.getRealTimeContext)
      ? PetMemory.getRealTimeContext()
      : { hour: new Date().getHours(), isWeekend: false, dayOfWeek: new Date().getDay() };

    const rt = PET_DIALOGUES.realTime;
    let pool = [];

    if (timeCtx.isFriday && rt.friday) pool.push(...rt.friday);
    else if (timeCtx.isMonday && rt.monday) pool.push(...rt.monday);
    else if (timeCtx.isWeekend && rt.weekend) pool.push(...rt.weekend);

    if (timeCtx.isMonthEnd && rt.monthEnd) pool.push(...rt.monthEnd);

    if (timeCtx.isLateNight && rt.lateNight) pool.push(...rt.lateNight);
    else if (timeCtx.timeSlot === 'dawn' && rt.dawn) pool.push(...rt.dawn);
    else if (timeCtx.timeSlot === 'noon' && rt.noon) pool.push(...rt.noon);
    else if (timeCtx.timeSlot === 'morning' && rt.morning) pool.push(...rt.morning);
    else if (timeCtx.timeSlot === 'afternoon' && rt.afternoon) pool.push(...rt.afternoon);
    else if (timeCtx.timeSlot === 'evening' && rt.evening) pool.push(...rt.evening);
    else if (timeCtx.timeSlot === 'night' && rt.night) pool.push(...rt.night);

    if (pool.length > 0) {
      list = pool;
    } else {
      list = rt.generalDays;
    }
  }
  // 2. หมวดความทรงจำ (Memory-Driven)
  else if (category === 'memory') {
    const memList = [];
    const mem = meta.petMemory;
    if (mem) {
      if (mem.daysTogether && mem.daysTogether >= 2) memList.push(...PET_DIALOGUES.memory.daysTogether);
      if (mem.favoriteDoc) memList.push(...PET_DIALOGUES.memory.favoriteDoc);
      if (mem.bondLevel && mem.bondLevel >= 3) memList.push(...PET_DIALOGUES.memory.highBond);
      if (mem.stats && mem.stats.totalPetted >= 5) memList.push(...PET_DIALOGUES.memory.pettedMilestone);
    }
    if (memList.length > 0) list = memList;
    else list = PET_DIALOGUES.memory.daysTogether;
  }
  // 3. หมวดอารมณ์ความรู้สึก (Mood-Driven)
  else if (category === 'mood' && meta.mood && PET_DIALOGUES.mood[meta.mood]) {
    list = PET_DIALOGUES.mood[meta.mood];
  }
  // 4. หมวดความเห็นอกเห็นใจ (Deep Empathy)
  else if (category === 'deepEmpathy') {
    list = PET_DIALOGUES.deepEmpathy;
  }
  // 5. ชนิดไฟล์
  else if (category === 'fileType' && meta.fileType && PET_DIALOGUES.fileType[meta.fileType]) {
    list = PET_DIALOGUES.fileType[meta.fileType];
  }
  // 6. เฟอร์นิเจอร์
  else if (category === 'environment' && meta.envType && PET_DIALOGUES.environment[meta.envType]) {
    list = PET_DIALOGUES.environment[meta.envType];
  }
  // 7. แกนนิสัย
  else if (category === 'personality' && meta.pet && meta.pet.personality) {
    const p = meta.pet.personality;
    const candidates = [];

    if (p.intelligence >= 65) candidates.push(...PET_DIALOGUES.smartThoughts);
    else if (p.intelligence <= 35) candidates.push(...PET_DIALOGUES.derpyThoughts);

    if (p.diligence >= 65) candidates.push(...PET_DIALOGUES.diligentThoughts);
    else if (p.diligence <= 35) candidates.push(...PET_DIALOGUES.lazyThoughts);

    if (p.energy >= 65) candidates.push(...PET_DIALOGUES.highEnergyThoughts);
    else if (p.energy <= 35) candidates.push(...PET_DIALOGUES.lowEnergyThoughts);

    if (p.talkativeness >= 65) candidates.push(...PET_DIALOGUES.talkativeThoughts);
    else if (p.talkativeness <= 35) candidates.push(...PET_DIALOGUES.quietThoughts);

    if (p.affection >= 65) candidates.push(...PET_DIALOGUES.affectionateThoughts);
    else if (p.affection <= 35) candidates.push(...PET_DIALOGUES.aloofThoughts);

    if (p.sociability >= 65) candidates.push(...PET_DIALOGUES.socialThoughts);
    else if (p.sociability <= 35) candidates.push(...PET_DIALOGUES.antisocialThoughts);

    if (candidates.length > 0) {
      list = candidates;
    }
  }

  const raw = list[Math.floor(Math.random() * list.length)];
  return formatDialogue(raw, meta);
}

export function formatDialogue(text, meta = {}) {
  if (!text) return 'เหมียว~';
  const safeMeta = meta || {};
  let res = text;
  const docName = safeMeta.docName || (typeof window !== 'undefined' && window.State && window.State.current ? window.State.current.name : 'เอกสารนี้');

  // วันเวลาจริงจาก PC
  let timeCtx = null;
  if (typeof PetMemory !== 'undefined' && PetMemory.getRealTimeContext) {
    timeCtx = PetMemory.getRealTimeContext();
  } else {
    const now = new Date();
    timeCtx = {
      dayName: ['วันอาทิตย์', 'วันจันทร์', 'วันอังคาร', 'วันพุธ', 'วันพฤหัสบดี', 'วันศุกร์', 'วันเสาร์'][now.getDay()],
      timeString: `${now.getHours().toString().padStart(2, '0')}:${now.getMinutes().toString().padStart(2, '0')}`,
      dateString: `${now.getDate()}/${now.getMonth() + 1}`,
      timeSlotName: 'วันนี้'
    };
  }

  // ตัวแปรความทรงจำ
  const daysVal = safeMeta.days || (safeMeta.petMemory ? safeMeta.petMemory.daysTogether : 1) || 1;
  const favDocVal = safeMeta.favoriteDoc || (safeMeta.petMemory?.favoriteDoc?.name) || docName;
  const pettedVal = safeMeta.totalPetted || (safeMeta.petMemory?.stats?.totalPetted) || 1;
  const bondVal = safeMeta.bondLevelName || (safeMeta.petMemory?.bondLevelName) || 'เพื่อนคู่ใจ';
  const moodVal = safeMeta.moodLabel || (safeMeta.petMemory?.mood) || 'สดชื่น';

  // ตัวแปรเพศ
  const gender = safeMeta.gender || safeMeta.pet?.gender || 'male';
  const isFemale = gender === 'female';

  res = res.replace(/\{doc\}/g, docName);
  res = res.replace(/\{name\}/g, safeMeta.petName || 'น้องแมว');
  res = res.replace(/\{petName\}/g, safeMeta.petName || 'น้องแมว');
  res = res.replace(/\{other\}/g, safeMeta.otherPetName || 'เพื่อนเหมียว');
  res = res.replace(/\{days\}/g, daysVal);
  res = res.replace(/\{favoriteDoc\}/g, favDocVal);
  res = res.replace(/\{totalPetted\}/g, pettedVal);
  res = res.replace(/\{bondLevelName\}/g, bondVal);
  res = res.replace(/\{mood\}/g, moodVal);
  res = res.replace(/\{dayName\}/g, timeCtx.dayName);
  res = res.replace(/\{timeString\}/g, timeCtx.timeString);
  res = res.replace(/\{dateString\}/g, timeCtx.dateString);
  res = res.replace(/\{timeSlotName\}/g, timeCtx.timeSlotName);
  res = res.replace(/\{particle\}/g, isFemale ? 'ค่ะ' : 'ครับ');
  res = res.replace(/\{particleSoft\}/g, isFemale ? 'นะคะ' : 'ฮะ');
  res = res.replace(/\{self\}/g, isFemale ? 'หนู' : 'ผม');
  res = res.replace(/\{title\}/g, isFemale ? 'สาวน้อย' : 'หนุ่มน้อย');
  res = res.replace(/\{gender\}/g, isFemale ? 'เพศเมีย' : 'เพศผู้');
  res = res.replace(/\{genderSymbol\}/g, isFemale ? '♀' : '♂');

  return res;
}
