// สุ่มบทสนทนาที่เหมาะสมตามบริบทและบุคลิกภาพ 6 แกน
export function getRandomDialogue(category, meta = {}) {
  let list = PET_DIALOGUES[category] || PET_DIALOGUES.docContext;

  if (category === 'fileType' && meta.fileType && PET_DIALOGUES.fileType[meta.fileType]) {
    list = PET_DIALOGUES.fileType[meta.fileType];
  } else if (category === 'environment' && meta.envType && PET_DIALOGUES.environment[meta.envType]) {
    list = PET_DIALOGUES.environment[meta.envType];
  } else if (category === 'personality' && meta.pet && meta.pet.personality) {
    const p = meta.pet.personality;
    const candidates = [];

    // ดึงบทสนทนาตามแกนนิสัยที่โดดเด่น
    if (p.intelligence >= 65) candidates.push(...PET_DIALOGUES.smartThoughts);
    else if (p.intelligence <= 35) candidates.push(...PET_DIALOGUES.derpyThoughts);

    if (p.diligence >= 65) candidates.push(...PET_DIALOGUES.diligentThoughts);
    else if (p.diligence <= 35) candidates.push(...PET_DIALOGUES.lazyThoughts);

    if (p.energy >= 65) candidates.push(...PET_DIALOGUES.highEnergyThoughts);
    else if (p.energy <= 35) candidates.push(...PET_DIALOGUES.lowEnergyThoughts);

    if (p.talkativeness >= 65) candidates.push(...PET_DIALOGUES.talkativeThoughts);
    else if (p.talkativeness <= 35) candidates.push(...PET_DIALOGUES.quietThoughts);

    if (p.affection >= 65) candidates.push(...PET_DIALOGUES.affectionateThoughts);
    else if (p.affection <= 35) candidates.push(...PET_DIALOGUES.aloofThoughts);

    if (p.sociability >= 65) candidates.push(...PET_DIALOGUES.socialThoughts);
    else if (p.sociability <= 35) candidates.push(...PET_DIALOGUES.antisocialThoughts);

    if (candidates.length > 0) {
      list = candidates;
    }
  }

  const raw = list[Math.floor(Math.random() * list.length)];
  return formatDialogue(raw, meta);
}

export function formatDialogue(text, meta = {}) {
  if (!text) return '';
  let res = text;
  const docName = meta.docName || (window.State && window.State.current ? window.State.current.name : 'เอกสารนี้');
  res = res.replace(/\{doc\}/g, docName);
  res = res.replace(/\{name\}/g, meta.petName || 'น้องแมว');
  res = res.replace(/\{other\}/g, meta.otherPetName || 'เพื่อนเหมียว');
  return res;
}
